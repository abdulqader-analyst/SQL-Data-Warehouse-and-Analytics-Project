-- Ranking Analysis

-- Which 5 Products generated the highest revenue
SELECT 
	P.product_name,
    SUM(S.sales_amount) AS Total_Revenue 
FROM gold.dim_products AS P
LEFT JOIN gold.facts_sales AS S
ON P.product_key = S.product_key
GROUP BY P.product_name
ORDER BY Total_Revenue DESC
LIMIT 5;


-- Use of Row_Number
SELECT * FROM (
SELECT 
	P.product_name,
    SUM(S.sales_amount) AS Total_Revenue,
    ROW_NUMBER() OVER(ORDER BY SUM(S.sales_amount) DESC) AS Rank_Product
FROM gold.dim_products AS P
LEFT JOIN gold.facts_sales AS S
ON P.product_key = S.product_key
GROUP BY P.product_name)t 
WHERE Rank_Product <= 5;


-- What the 5 worst Performing Products
SELECT 
	P.product_name,
    SUM(S.sales_amount) AS Total_Revenue 
FROM gold.dim_products AS P
JOIN gold.facts_sales AS S
ON P.product_key = S.product_key
GROUP BY P.product_name
ORDER BY Total_Revenue ASC    -- Just I change DESC to ASC
LIMIT 5;


-- Which 5 subcategories  generated the highest revenue
SELECT 
	P.subcategory,
    SUM(S.sales_amount) AS Total_Revenue 
FROM gold.dim_products AS P
JOIN gold.facts_sales AS S
ON P.product_key = S.product_key
GROUP BY P.subcategory
ORDER BY Total_Revenue DESC   
